from abc import ABC, abstractmethod

class User(ABC):

    def __init__(self, name, phone):
        self._name = name
        self._phone = phone
        self._wallet_balance = 0

    def add_to_wallet(self, amount):
        if amount >= 0:
          self._wallet_balance += amount

    @abstractmethod
    def notify(self, message):
        pass

    @abstractmethod
    def display_profile(self):
        pass



"""## 2. Customer

`Customer` inherits from `User`.

Additional data:
- `address`
- `order_history`, initially an empty list

Required behaviour:
- `notify(message)` prints a customer-specific notification.
- `display_profile()` prints the customer name, phone, wallet balance, and address.
- `place_order(restaurant, items)` creates an `Order`, adds it to `order_history`, and returns the created order.
"""

