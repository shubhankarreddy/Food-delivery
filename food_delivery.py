"""## 6. DeliveryPartner

`DeliveryPartner` inherits from `User`.

Additional attributes:

- `vehicle`
- `is_available`, initially `True`
- `rating`, initially `0.0`

Required behaviour:

**`accept_order(order)`**
- changes the order status to `Accepted`
- makes the delivery partner unavailable

**`deliver(order, otp)`**
- verifies the OTP before completing delivery
- leaves the order as `Accepted` when the OTP is incorrect
- keeps the delivery partner unavailable when the OTP is incorrect
- changes the order status to `Delivered` when the OTP is correct
- makes the delivery partner available again after successful delivery
"""

class DeliveryPartner(User):

    def init(self, name, phone, vehicle):

        super().__init__(name,phone)

        self.vehicle = vehicle

        self.is_available = True

        self.rating = 0.0

    def notify(self, message):

        self.message = message

        print("Notification: ", message, "for delivery partner: ", self._name)

    def display_profile(self):

        print("Name: ", self._name)

        print("Phone: ", self._phone)

        print("availibility: ", self.is_available)

        print("Rating: ", self.rating)

    def accept_order(self, order):

        order.update_status("Accepted")

        self.is_available = False

    def deliver(self, order, otp):

      if order.verify_otp(otp):
        order.update_status("Delivered")
        self.is_available = True

